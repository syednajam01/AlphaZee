const { chromium, webkit } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { installVendorFixture } = require('./vendor_matrix_fixtures.cjs');
const origin = process.env.SMOKE_ORIGIN || 'http://127.0.0.1:8080';
(async () => {
  const engine = process.env.VENDOR_ENGINE === 'webkit' ? webkit : chromium;
  const browser = await engine.launch(engine === chromium ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined } : {});
  try {
    for (const width of [390, 768, 1440]) {
      const page = await browser.newPage({ viewport: { width, height: 900 }, reducedMotion: 'reduce' });
      const errors = []; page.on('pageerror', error => errors.push(error.message));
      const state = await installVendorFixture(page);
      // Even malformed extra fields must never be rendered by the stock UI.
      state.items[0].price_minor = 987654321; state.items[0].profit_margin = 'SAMPLE private margin';
      await page.goto(origin + '/vendor', { waitUntil: 'domcontentloaded' });
      await page.locator('#vp-matrix-count-101').waitFor();
      assert.equal(await page.locator('.vp-stock-group').count(), 3, 'same title must not merge different product IDs');
      assert.equal(await page.locator('.vp-matrix-row').count(), 8);
      assert((await page.locator('#vp-card-104 .vp-matrix-cost').textContent()).includes('1,450.50'));
      assert((await page.locator('#vp-card-201 .vp-matrix-cost').textContent()).includes('Not agreed'));
      const body = await page.locator('body').textContent();
      assert(!body.includes('987654321') && !body.includes('9,876,543.21') && !body.includes('SAMPLE private margin'));
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
      if (process.env.VENDOR_ARTIFACTS) {
        fs.mkdirSync(process.env.VENDOR_ARTIFACTS, { recursive: true });
        await page.screenshot({ path: `${process.env.VENDOR_ARTIFACTS}/matrix-${width}.png`, fullPage: true });
      }
      const input = id => page.locator(`#vp-matrix-count-${id}`);
      const row = id => page.locator(`#vp-card-${id}`);
      const save = id => page.locator(`#vp-save-row-${id}`);
      const groupSave = page.locator('.vp-stock-group').first().locator('.vp-save-all-btn');
      await input(101).fill(''); assert(await groupSave.isDisabled());
      await input(101).fill('1.5'); assert(await groupSave.isDisabled());
      await input(101).fill('12'); await input(102).fill('13');
      await groupSave.click(); await page.waitForFunction(() => document.querySelector('.vp-notice')?.textContent.includes('2 saved'));
      await page.waitForFunction(() => document.querySelector('#vp-row-status-102')?.textContent === 'Saved');
      assert.deepEqual(state.calls.map(call => call.id), [101, 102]);
      assert(state.calls.every(call => call.body.expected_version === 2 && call.body.reason === 'manual_count'));
      await input(101).fill('15'); await input(102).fill('14'); state.failures.set(102, 503);
      await groupSave.click(); await page.waitForFunction(() => document.querySelector('.vp-notice')?.textContent.includes('1 not saved'));
      assert.equal(await input(102).inputValue(), '14');
      assert((await row(102).textContent()).includes('Not saved'));
      const beforeRetry = state.calls.length;
      await groupSave.click(); await page.waitForFunction(() => document.querySelector('.vp-notice')?.textContent.includes('1 saved · 0 shortage reports · 0 not saved'));
      assert.deepEqual(state.calls.slice(beforeRetry).map(call => call.id), [102], 'successful row must not be submitted twice');
      state.failures.set(101, 409); await input(101).fill('17'); await save(101).click();
      await page.waitForFunction(() => document.querySelector('#vp-card-101 .vp-recorded-count')?.textContent.includes('20'));
      assert.equal(await input(101).inputValue(), '17'); assert(await save(101).isDisabled());
      await row(101).locator('.vp-use-latest').click(); assert.equal(await input(101).inputValue(), '20');
      await input(101).fill('18'); await save(101).click();
      await page.waitForFunction(() => document.querySelector('#vp-card-101 .vp-recorded-count')?.textContent.includes('18'));
      const stockBeforeShortage = state.items.find(item => item.variant_id === 101).allocated_on_hand;
      await input(101).fill('1'); const beforeWarning = state.calls.length;
      await save(101).click(); await page.locator('#vp-confirm-matrix').waitFor();
      assert.equal(state.calls.length, beforeWarning, 'confirmation must precede every below-hold request');
      await page.locator('#vp-cancel-count').click(); assert.equal(await input(101).inputValue(), '1');
      await save(101).click(); await page.locator('#vp-confirm-matrix').click();
      await page.waitForFunction(() => document.querySelector('#vp-row-status-101')?.textContent.includes('Shortage reported'));
      assert.equal(state.items.find(item => item.variant_id === 101).allocated_on_hand, stockBeforeShortage);
      assert.equal(state.items.find(item => item.variant_id === 101).held_quantity, 3);
      assert.equal(await row(101).locator('.vp-matrix-available').evaluate(el => el.lastChild.textContent), '0');
      await page.locator('#vp-count-open-103').click();
      await page.locator('#vp-new-count').fill('14'); await page.locator('#vp-note').fill('SAMPLE shelf count');
      await page.locator('#vp-submit-count').click(); await page.locator('#vp-count-form').waitFor({ state: 'detached' });
      assert(state.calls.some(call => call.id === 103 && call.body.note === 'SAMPLE shelf count'));
      await page.locator('#vp-shortage-open-103').click(); await page.locator('#vp-shortage-count').fill('0');
      await page.locator('#vp-shortage-note').fill('SAMPLE damaged unit'); await page.locator('#vp-submit-shortage').click();
      await page.locator('#vp-shortage-form').waitFor({ state: 'detached' });
      assert(state.calls.some(call => call.kind === 'shortage' && call.body.note === 'SAMPLE damaged unit'));
      await page.locator('#vp-history-btn').click(); await page.locator('.vp-history-table').waitFor();
      await page.keyboard.press('Escape');
      await input(104).fill('17'); await page.locator('#vp-refresh-btn').click(); await input(104).waitFor();
      assert.equal(await input(104).inputValue(), '17');
      await input(101).fill('19'); await page.locator('#vp-stock-search').fill('Chalk');
      await page.waitForFunction(() => document.querySelectorAll('.vp-matrix-row').length === 3);
      await page.locator('#vp-clear-search').click(); await input(101).waitFor(); assert.equal(await input(101).inputValue(), '19');
      // A fresh server count must not silently rebase a pending local edit.
      const external = state.items.find(item => item.variant_id === 104); external.version++; external.allocated_on_hand = 15;
      await page.evaluate(() => window.dispatchEvent(new Event('focus')));
      await page.waitForFunction(() => document.querySelector('#vp-card-104 .vp-recorded-count')?.textContent.includes('15'));
      assert.equal(await input(104).inputValue(), '17'); assert(await save(104).isDisabled());
      await row(104).locator('.vp-use-latest').click();
      await input(101).fill('22'); await input(102).fill('15'); state.failures.set(101, 401);
      const beforeExpiry = state.calls.length;
      await groupSave.click(); await page.locator('#vp-login-form').waitFor();
      assert.equal(state.calls.length, beforeExpiry + 1, 'expiry must stop the remaining batch');
      assert.equal(await page.locator('.vp-matrix-row').count(), 0);
      assert(!(await page.locator('body').textContent()).includes('1,400'));
      state.authenticated = true;
      await page.reload({ waitUntil: 'domcontentloaded' }); await input(101).waitFor();
      assert.equal(await input(101).inputValue(), String(state.items.find(item => item.variant_id === 101).allocated_on_hand));
      await page.locator('#vp-logout-btn').click(); await page.locator('#vp-login-form').waitFor();
      assert.equal(await page.locator('.vp-matrix-row').count(), 0);
      assert.deepEqual(errors, []);
      await page.close(); console.log(`PASS: vendor matrix ${width}px; batches, partial retry, conflict, holds, drafts, notes, history, expiry and logout`);
    }
    // Fifty-row pagination must retain hidden drafts and limit Save All to shown rows.
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const pagination = await installVendorFixture(page, { pagination: true });
    await page.goto(origin + '/vendor', { waitUntil: 'domcontentloaded' }); await page.locator('#vp-matrix-count-101').waitFor();
    await page.locator('#vp-matrix-count-101').fill('12'); await page.locator('#vp-next-page').click();
    await page.waitForFunction(() => document.querySelectorAll('.vp-matrix-row').length === 2);
    assert((await page.locator('.vp-draft-total').textContent()).includes('1 unsaved'));
    await page.locator('#vp-prev-page').click(); await page.locator('#vp-matrix-count-101').waitFor();
    assert.equal(await page.locator('#vp-matrix-count-101').inputValue(), '12');
    await page.locator('#vp-next-page').click(); await page.waitForFunction(() => document.querySelectorAll('.vp-matrix-row').length === 2);
    pagination.items.splice(50);
    await page.evaluate(() => window.dispatchEvent(new Event('focus')));
    await page.locator('#vp-first-page').click(); await page.locator('#vp-matrix-count-101').waitFor();
    assert.equal(await page.locator('#vp-matrix-count-101').inputValue(), '12');
    await page.locator('#vp-stock-search').fill('SAMPLE no matching rows');
    await page.locator('.vp-empty-state').waitFor();
    assert((await page.locator('.vp-draft-total').textContent()).includes('1 unsaved'));
    await page.locator('.vp-discard-drafts').click(); await page.locator('#vp-confirm-matrix').click();
    await page.locator('#vp-clear-search').click(); await page.locator('#vp-matrix-count-101').waitFor();
    assert.equal(await page.locator('#vp-matrix-count-101').inputValue(), '10');
    await page.close(); console.log('PASS: cross-page drafts and explicit discard; no application DB writes');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
